import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { RESEARCH_NAMES } from "./research-names.ts";
import { readToolConfig, TOOL_CONFIG } from "./tool-config.ts";
import type { Check } from "./types.ts";

// `c-f-x check names`: public text never names a vendor known only from
// research (docs/conventions.md, section 14). The list of those names is
// stored as SHA-256 hashes (research-names.ts), so the public repository does
// not spell them out. A tool lists the vendors it integrates under "vendors"
// in its c-f-x.json, and may name those. New in the kit.

/** One research-only name: the SHA-256 hex of its normal form, and whether it is also a dictionary word. */
export type ResearchName = { sha256: string; word: boolean };
export type NameList = readonly ResearchName[];

/** Where a name was found: the line, from 1, and the name as the text writes it. */
export type Found = { line: number; written: string };

// A word: letters and digits, which may hold dots, hyphens and underscores
// between them, as in a domain name, a hyphenated name or a constant.
const TOKEN = /[A-Za-z0-9]+(?:[._-][A-Za-z0-9]+)*/g;
const JOINS = /[._-]/;
// Names are matched up to this many words long.
const MAX_WORDS = 4;

/** A name's normal form: lower case, without notes in brackets, its words joined by one space. */
export function normalName(name: string): string {
  const bare = name.toLowerCase().replace(/\([^)]*\)/g, " ");
  return (bare.match(TOKEN) ?? []).join(" ");
}

export const nameHash = (normal: string): string =>
  createHash("sha256").update(normal).digest("hex");

// A one-word name the dictionary holds, alone or as a plural.
const isWord = (normal: string, dictionary: ReadonlySet<string>): boolean =>
  !normal.includes(" ") &&
  (dictionary.has(normal) || (normal.endsWith("s") && dictionary.has(normal.slice(0, -1))));

/**
 * The list for `names`: each name once, by the hash of its normal form. A
 * one-word name the dictionary holds, alone or as a plural, is marked a word,
 * so the scan finds it only where prose writes it as a name.
 */
export function nameList(names: string[], dictionary: ReadonlySet<string>): ResearchName[] {
  const byHash = new Map<string, ResearchName>();
  for (const name of names) {
    const normal = normalName(name);
    if (normal === "") continue;
    const sha256 = nameHash(normal);
    byHash.set(sha256, { sha256, word: isWord(normal, dictionary) });
  }
  return [...byHash.values()].toSorted((a, b) => (a.sha256 < b.sha256 ? -1 : 1));
}

/** The source text of research-names.ts for `list`: hashes only. */
export function researchNamesModule(list: NameList): string {
  return [
    "// Generated by scripts/hash-names.mjs: never edit by hand. Each entry is the",
    "// SHA-256 of a research-only name in its normal form (normalName in",
    "// names.ts), so this public file does not spell the names out.",
    'import type { ResearchName } from "./names.ts";',
    "",
    "export const RESEARCH_NAMES: readonly ResearchName[] = [",
    ...list.map((e) => `  { sha256: "${e.sha256}", word: ${e.word} },`),
    "];",
    "",
  ].join("\n");
}

type Token = { text: string; start: number; end: number };

const tokensOf = (line: string): Token[] =>
  [...line.matchAll(TOKEN)].map((m) => ({
    text: m[0],
    start: m.index,
    end: m.index + m[0].length,
  }));

// A dictionary word counts as a name only where prose uses it as one: written
// with a capital and then lower case, after a lower-case word or a comma on
// the same line, and not as code (`X.from`, `X(`, `X<T>`, `X[i]`).
function writtenAsName(line: string, token: Token): boolean {
  return (
    /^[A-Z][a-z]/.test(token.text) &&
    /[a-z0-9,][ \t]+$/.test(line.slice(0, token.start)) &&
    !/^(\.[A-Za-z_]|[(<[])/.test(line.slice(token.end))
  );
}

/**
 * Every research-only name in `text`, in the order it appears. Names that are
 * also words are looked for only when `prose` is true: in code, a capitalised
 * word is far more often a type than a name.
 */
export function findNames(text: string, list: NameList, prose: boolean): Found[] {
  const banned = new Map(list.filter((e) => prose || !e.word).map((e) => [e.sha256, e.word]));
  const found: Found[] = [];
  text.split("\n").forEach((line, index) => {
    const tokens = tokensOf(line);
    tokens.forEach((first, i) => {
      // Whole words, then runs of words split only by spaces or tabs.
      let words = first.text.toLowerCase();
      for (let n = 1; n <= MAX_WORDS && i + n <= tokens.length; n++) {
        const last = tokens[i + n - 1];
        if (last === undefined) break;
        if (n > 1) {
          const prev = tokens[i + n - 2];
          if (prev === undefined || !/^[ \t]+$/.test(line.slice(prev.end, last.start))) break;
          words = `${words} ${last.text.toLowerCase()}`;
        }
        const word = banned.get(nameHash(words));
        if (word === undefined || (word && (n > 1 || !writtenAsName(line, first)))) continue;
        found.push({ line: index + 1, written: line.slice(first.start, last.end) });
        return;
      }
      // The parts of a joined word, as in "vendor.io", "vendor-cloud" or "VENDOR_KEY".
      if (!JOINS.test(first.text)) return;
      for (const part of first.text.split(JOINS)) {
        if (banned.get(nameHash(part.toLowerCase())) === false)
          found.push({ line: index + 1, written: part });
      }
    });
  });
  return found;
}

// The files whose text is prose, where a name that is also a word is looked for.
const PROSE = /\.(md|mdx|html?|txt)$/;

// The files git tracks under `root`, or undefined when it is not a git repository.
function trackedFiles(root: string): string[] | undefined {
  try {
    const out = execFileSync("git", ["-C", root, "ls-files", "-z"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return out.split("\0").filter((f) => f !== "");
  } catch {
    // git refuses a folder outside a repository; the caller reports that.
    return undefined;
  }
}

/** The names check over a list passed in. The kit registers it with RESEARCH_NAMES. */
export function namesCheck(list: NameList): Check {
  return {
    name: "names",
    summary: "no tracked file names a vendor known only from research",
    async run({ root }) {
      const files = trackedFiles(root);
      if (files === undefined)
        return ["names: not a git repository, so the tracked files are unknown"];
      let vendors: string[] = [];
      if (existsSync(path.join(root, TOOL_CONFIG))) {
        const config = readToolConfig(root);
        if (!config.ok) return config.problems;
        vendors = config.value.vendors;
      }
      const allowed = new Set(vendors.map((v) => nameHash(normalName(v))));
      const banned = list.filter((e) => !allowed.has(e.sha256));
      const problems: string[] = [];
      for (const file of files) {
        const full = path.join(root, file);
        if (!existsSync(full)) continue;
        const bytes = readFileSync(full);
        if (bytes.includes(0)) continue;
        for (const { line, written } of findNames(bytes.toString("utf8"), banned, PROSE.test(file)))
          problems.push(
            `${file}:${line}: names "${written}", which is known only from research (docs/conventions.md, section 14)`,
          );
      }
      return problems;
    },
  };
}

export const names: Check = namesCheck(RESEARCH_NAMES);
